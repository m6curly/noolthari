import { createClient } from 'https://esm.sh/@supabase/supabase-js@2.57.4';

const headers = { 'Content-Type': 'application/json' };
const escapeHtml = (value: unknown) =>
  String(value ?? '').replace(/[&<>"']/g, (char) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[char] || char));

const money = (value: unknown) =>
  `₹${Number(value || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const readable = (value: unknown) =>
  String(value ?? 'updated').replaceAll('_', ' ');

function renderEmail(title: string, intro: string, rows: Array<[string, unknown]>) {
  const detailRows = rows.map(([label, value]) => `
    <tr>
      <td style="padding:11px 0;border-bottom:1px solid #eee;color:#7a817c;width:38%;vertical-align:top">${escapeHtml(label)}</td>
      <td style="padding:11px 0;border-bottom:1px solid #eee;color:#253d39;font-weight:600;vertical-align:top">${escapeHtml(value)}</td>
    </tr>
  `).join('');

  return `<!doctype html>
<html><body style="margin:0;background:#f6f2eb;font-family:Arial,Helvetica,sans-serif;color:#33433f">
  <div style="max-width:640px;margin:28px auto;padding:34px;background:#fffefa;border:1px solid #e8dfd1;border-radius:12px">
    <div style="font-size:12px;letter-spacing:3px;font-weight:700;color:#9b783e">NOOLTHARI™ · ADMIN ALERT</div>
    <h1 style="margin:18px 0 10px;font-family:Georgia,serif;font-size:28px;font-weight:normal;color:#123e42">${escapeHtml(title)}</h1>
    <p style="line-height:1.65;color:#56645e">${escapeHtml(intro)}</p>
    <table role="presentation" style="width:100%;border-collapse:collapse;margin-top:22px">${detailRows}</table>
    <p style="margin-top:28px;font-size:12px;color:#85877f">This operational alert was generated by the NOOLTHARI store.</p>
  </div>
</body></html>`;
}

Deno.serve(async (request: Request) => {
  if (request.method !== 'POST') {
    return new Response(JSON.stringify({ message: 'Method not allowed.' }), { status: 405, headers });
  }

  const expectedSecret = Deno.env.get('NOTIFICATION_CRON_SECRET') || '';
  const suppliedSecret = request.headers.get('x-cron-secret')
    || request.headers.get('Authorization')?.replace(/^Bearer\s+/i, '')
    || '';

  if (!expectedSecret || suppliedSecret !== expectedSecret) {
    return new Response(JSON.stringify({ message: 'Forbidden.' }), { status: 403, headers });
  }

  const supabaseUrl = Deno.env.get('SUPABASE_URL');
  const serviceKey = Deno.env.get('SUPABASE_SECRET_KEY') || Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
  const resendKey = Deno.env.get('RESEND_API_KEY');
  const fromEmail = Deno.env.get('NOTIFICATION_FROM_EMAIL');
  const adminEmail = Deno.env.get('ADMIN_NOTIFICATION_TO') || 'noolthari6@gmail.com';

  if (!supabaseUrl || !serviceKey || !resendKey || !fromEmail) {
    return new Response(JSON.stringify({
      message: 'Email delivery is not configured. Check Supabase and Resend Edge Function secrets.',
    }), { status: 503, headers });
  }

  const admin = createClient(supabaseUrl, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  const body = await request.json().catch(() => ({}));
  const limit = Number.isInteger(body?.limit) ? Math.min(50, Math.max(1, body.limit)) : 20;

  const claim = await admin.rpc('claim_admin_email_notifications', { p_limit: limit });
  if (claim.error) {
    console.error('Admin notification queue claim failed:', claim.error.message);
    return new Response(JSON.stringify({ message: 'Could not claim admin email notifications.' }), { status: 500, headers });
  }

  let sent = 0;
  let failed = 0;

  for (const item of claim.data || []) {
    try {
      let subject = 'NOOLTHARI store update';
      let title = 'A store event needs your attention';
      let intro = 'A new event was recorded in your NOOLTHARI store.';
      let rows: Array<[string, unknown]> = [
        ['Event', readable(item.event_type)],
        ['Reference', item.entity_id],
      ];

      if (item.event_type === 'signup') {
        const result = await admin.from('profiles')
          .select('id,name,email,phone,created_at')
          .eq('id', item.entity_id)
          .maybeSingle();
        if (result.error || !result.data) throw new Error(`SIGNUP_NOT_FOUND: ${result.error?.message || ''}`);
        const profile = result.data;
        subject = 'New customer registered | NOOLTHARI™';
        title = 'A new customer has signed up';
        intro = 'A new customer account has been created on your store.';
        rows = [
          ['Customer', profile.name || 'Not provided'],
          ['Email', profile.email || 'Not provided'],
          ['Phone', profile.phone || 'Not provided'],
          ['Registered', profile.created_at ? new Date(profile.created_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) : '—'],
          ['Customer ID', profile.id],
        ];
      } else if (item.event_type === 'order_created' || item.event_type === 'order_status') {
        const result = await admin.from('orders').select(`
          id,order_number,total,status,payment_provider,customer_name,customer_email,
          shipping_full_name,shipping_phone,shipping_city,shipping_state,shipping_postal_code,created_at,
          profiles(name,email,phone),
          order_items(product_name,quantity,line_total)
        `).eq('id', item.entity_id).maybeSingle();
        if (result.error || !result.data) throw new Error(`ORDER_NOT_FOUND: ${result.error?.message || ''}`);
        const order = result.data as any;
        const profile = Array.isArray(order.profiles) ? order.profiles[0] : order.profiles;
        const customer = order.customer_name || order.shipping_full_name || profile?.name || 'Customer';
        const email = order.customer_email || profile?.email || 'Not provided';
        subject = item.event_type === 'order_created'
          ? `New order ${order.order_number || ''} | NOOLTHARI™`
          : `Order ${order.order_number || ''} · ${readable(order.status)} | NOOLTHARI™`;
        title = item.event_type === 'order_created' ? 'A new order has been placed' : 'An order status has changed';
        intro = item.event_type === 'order_created'
          ? 'A new order has been recorded on your store. Check its payment status before dispatch.'
          : `The order status is now ${readable(order.status)}.`;
        const itemSummary = (order.order_items || [])
          .map((line: any) => `${line.product_name} × ${Number(line.quantity || 0)} (${money(line.line_total)})`)
          .join(' · ');
        rows = [
          ['Order number', order.order_number || order.id],
          ['Customer', customer],
          ['Customer email', email],
          ['Phone', order.shipping_phone || profile?.phone || 'Not provided'],
          ['Items', itemSummary || 'Order items are not available'],
          ['Order total', money(order.total)],
          ['Payment source', order.payment_provider || 'Not recorded'],
          ['Order status', readable(order.status)],
          ['Order time', order.created_at ? new Date(order.created_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) : '—'],
        ];
      } else if (item.event_type === 'return_created' || item.event_type === 'return_status') {
        const result = await admin.from('return_requests').select(`
          id,reason,description,status,created_at,
          orders(order_number,total),
          products(saree_name),
          profiles(name,email,phone)
        `).eq('id', item.entity_id).maybeSingle();
        if (result.error || !result.data) throw new Error(`RETURN_NOT_FOUND: ${result.error?.message || ''}`);
        const row = result.data as any;
        const order = Array.isArray(row.orders) ? row.orders[0] : row.orders;
        const product = Array.isArray(row.products) ? row.products[0] : row.products;
        const customer = Array.isArray(row.profiles) ? row.profiles[0] : row.profiles;
        subject = item.event_type === 'return_created'
          ? `New return request · ${order?.order_number || ''} | NOOLTHARI™`
          : `Return status changed · ${order?.order_number || ''} | NOOLTHARI™`;
        title = item.event_type === 'return_created' ? 'A customer requested a return' : 'A return status has changed';
        intro = item.event_type === 'return_created'
          ? 'A new return request has been submitted and needs review.'
          : `The return request status is now ${readable(row.status)}.`;
        rows = [
          ['Order number', order?.order_number || 'Not available'],
          ['Customer', customer?.name || 'Not available'],
          ['Customer email', customer?.email || 'Not available'],
          ['Product', product?.saree_name || 'Not available'],
          ['Reason', row.reason || 'Not provided'],
          ['Description', row.description || 'Not provided'],
          ['Return status', readable(row.status)],
          ['Request time', row.created_at ? new Date(row.created_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) : '—'],
        ];
      } else if (item.event_type === 'shipment_status') {
        const result = await admin.from('shipments').select(`
          id,status,carrier,tracking_number,tracking_url,updated_at,
          orders(order_number,total,customer_name,customer_email,customer_phone,
            shipping_full_name,shipping_phone,profiles(name,email,phone))
        `).eq('id', item.entity_id).maybeSingle();
        if (result.error || !result.data) throw new Error(`SHIPMENT_NOT_FOUND: ${result.error?.message || ''}`);
        const shipment = result.data as any;
        const order = Array.isArray(shipment.orders) ? shipment.orders[0] : shipment.orders;
        const profile = Array.isArray(order?.profiles) ? order.profiles[0] : order?.profiles;
        subject = `Shipment update · ${order?.order_number || ''} | NOOLTHARI™`;
        title = 'A shipment status has changed';
        intro = `The shipment status is now ${readable(shipment.status)}.`;
        rows = [
          ['Order number', order?.order_number || 'Not available'],
          ['Customer', order?.customer_name || order?.shipping_full_name || profile?.name || 'Not available'],
          ['Customer email', order?.customer_email || profile?.email || 'Not available'],
          ['Carrier', shipment.carrier || 'Not recorded'],
          ['Tracking number', shipment.tracking_number || 'Not recorded'],
          ['Shipment status', readable(shipment.status)],
          ['Order total', money(order?.total)],
          ['Updated', shipment.updated_at ? new Date(shipment.updated_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) : '—'],
        ];
      } else if (item.event_type === 'payment_status') {
        const result = await admin.from('payments').select(`
          id,amount,currency,status,payment_method,gateway,updated_at,
          orders(order_number,total,customer_name,customer_email,customer_phone,
            shipping_full_name,shipping_phone,profiles(name,email,phone))
        `).eq('id', item.entity_id).maybeSingle();
        if (result.error || !result.data) throw new Error(`PAYMENT_NOT_FOUND: ${result.error?.message || ''}`);
        const payment = result.data as any;
        const order = Array.isArray(payment.orders) ? payment.orders[0] : payment.orders;
        const profile = Array.isArray(order?.profiles) ? order.profiles[0] : order?.profiles;
        subject = `Payment ${readable(payment.status)} · ${order?.order_number || ''} | NOOLTHARI™`;
        title = 'A payment status has changed';
        intro = `A payment is now marked ${readable(payment.status)}. Check the order before dispatch or refund action.`;
        rows = [
          ['Order number', order?.order_number || 'Not available'],
          ['Customer', order?.customer_name || order?.shipping_full_name || profile?.name || 'Not available'],
          ['Customer email', order?.customer_email || profile?.email || 'Not available'],
          ['Payment amount', `${money(payment.amount)} ${payment.currency || 'INR'}`],
          ['Payment status', readable(payment.status)],
          ['Payment method', payment.payment_method || payment.gateway || 'Not recorded'],
          ['Updated', payment.updated_at ? new Date(payment.updated_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) : '—'],
        ];
      } else if (item.event_type === 'contact_message') {
        const result = await admin.from('contact_messages')
          .select('id,name,email,subject,message,created_at')
          .eq('id', item.entity_id)
          .maybeSingle();
        if (result.error || !result.data) throw new Error(`CONTACT_MESSAGE_NOT_FOUND: ${result.error?.message || ''}`);
        const message = result.data;
        subject = `New website enquiry: ${message.subject} | NOOLTHARI™`;
        title = 'A new website enquiry has arrived';
        intro = 'A customer has sent a message through the NOOLTHARI contact form.';
        rows = [
          ['Name', message.name],
          ['Email', message.email],
          ['Subject', message.subject],
          ['Message', message.message],
          ['Received', message.created_at ? new Date(message.created_at).toLocaleString('en-IN', { timeZone: 'Asia/Kolkata' }) : '—'],
        ];
      }

      const html = renderEmail(title, intro, rows);
      const plainText = [
        title,
        intro,
        ...rows.map(([label, value]) => `${label}: ${String(value ?? '')}`),
        'NOOLTHARI™',
      ].join('\n');

      const response = await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: {
          Authorization: `Bearer ${resendKey}`,
          'Content-Type': 'application/json',
          'Idempotency-Key': `noolthari-admin-${item.id}`,
        },
        body: JSON.stringify({
          from: fromEmail,
          to: [adminEmail],
          subject,
          html,
          text: plainText,
        }),
      });

      const provider = await response.json().catch(() => ({}));
      if (!response.ok) {
        throw new Error(`RESEND_${response.status}: ${String(provider?.message || 'Email delivery failed')}`);
      }

      const updated = await admin.from('admin_email_notifications')
        .update({
          status: 'sent',
          sent_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
          last_error: null,
        })
        .eq('id', item.id);
      if (updated.error) throw new Error(`QUEUE_UPDATE_FAILED: ${updated.error.message}`);
      sent += 1;
    } catch (error) {
      const message = error instanceof Error ? error.message : 'UNKNOWN_NOTIFICATION_ERROR';
      const retryMinutes = Math.min(60, Math.max(5, Number(item.attempts || 1) * 5));
      await admin.from('admin_email_notifications')
        .update({
          status: 'failed',
          last_error: message.slice(0, 500),
          available_at: new Date(Date.now() + retryMinutes * 60_000).toISOString(),
          updated_at: new Date().toISOString(),
        })
        .eq('id', item.id);
      console.error('Admin notification delivery failed:', item.id, message);
      failed += 1;
    }
  }

  return new Response(JSON.stringify({
    processed: sent + failed,
    sent,
    failed,
    recipient: adminEmail,
  }), { status: 200, headers });
});
